package com.operators.programs;

public class logical {
	public static void main(String[] args) {

		System.out.println(10>2 && 4<8);
		System.out.println(1>2 && 4<8);
		System.out.println(10>2 || 4<8);
		System.out.println(10>2 || 11<8);
		System.out.println(10>20 && 22<8);
		
		boolean ak=false;
		System.out.println(!ak);
		
		
	}

}
