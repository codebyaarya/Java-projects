package com.operators.programs;

public class unary {
	public static void main(String []args) {
		int x=10;
		System.out.println(x++);//first print then increment
		System.out.println(x);
		
		int y=8;
		System.out.println(++y);//first increment then print
		System.out.println(y);
				
	}

}
